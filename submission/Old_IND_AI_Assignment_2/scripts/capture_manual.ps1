$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath (Split-Path -Parent $PSScriptRoot)

$pythonExecutable = 'python'
if (Test-Path -LiteralPath '.venv\Scripts\python.exe') {
    $pythonExecutable = '.\.venv\Scripts\python.exe'
}
$prologExecutable = 'swipl'
if (Test-Path -LiteralPath 'tools\swipl\bin\swipl.exe') {
    $prologExecutable = '.\tools\swipl\bin\swipl.exe'
}

Write-Host 'Run each program and use Snipping Tool manually. No screenshot is generated by this script.'
& $pythonExecutable problem1/run_analysis.py
if ($LASTEXITCODE -ne 0) { throw 'Bayesian analysis failed' }
Read-Host 'Capture Bayesian queries and all three dataset tables; press Enter when done'

foreach ($figure in @('network.png', 'estimator_comparison.png')) {
    Write-Host ('Open problem1\outputs\' + $figure + ' in your image viewer and capture it.')
    Read-Host 'Press Enter after saving the genuine screenshot'
}

foreach ($scenario in @('original', 'extended')) {
    foreach ($search in @('gbfs', 'astar')) {
        & $pythonExecutable problem2/run_planner.py --scenario $scenario --search $search
        if ($LASTEXITCODE -ne 0) { throw 'Planning failed' }
        Read-Host ('Save screenshots\problem2_' + $scenario + '_' + $search + '.png; press Enter when done')
    }
}

& $prologExecutable -q -s problem3/royal_archive_access.pl -g main -t halt
if ($LASTEXITCODE -ne 0) { throw 'Proof execution failed' }
Read-Host 'Save screenshots\problem3_proof.png with C15 = [] and SELF-TEST PASS; press Enter when done'
Write-Host 'Rebuild reports and verify the strict submission package:'
Write-Host 'python scripts/build_reports.py'
Write-Host 'python scripts/package_submission.py --require-screenshots'
